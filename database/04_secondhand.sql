USE campushub_secondhand;
CREATE TABLE IF NOT EXISTS tb_category (
 id BIGINT NOT NULL, name VARCHAR(50) NOT NULL, sort INT NOT NULL DEFAULT 0, create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY uk_name(name)
) ENGINE=InnoDB COMMENT='二手物品分类';
CREATE TABLE IF NOT EXISTS tb_item (
 id BIGINT NOT NULL, seller_id BIGINT NOT NULL, name VARCHAR(255) NOT NULL, price INT NOT NULL COMMENT '价格（分）',
 image VARCHAR(500) NOT NULL DEFAULT '', category_id BIGINT NOT NULL, condition_desc VARCHAR(100) NOT NULL DEFAULT '' COMMENT '成色描述',
 description VARCHAR(1000) NOT NULL DEFAULT '', trade_location VARCHAR(255) NOT NULL DEFAULT '', status TINYINT NOT NULL DEFAULT 1 COMMENT '1在售 2预订 3已售 0下架',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY idx_seller_id(seller_id), KEY idx_category_id(category_id), KEY idx_status(status)
) ENGINE=InnoDB COMMENT='校园二手物品';
